const db = new sqlite3.Database(path.join(__dirname, '..', 'database.db'));

db.serialize(() => {
  const stmt = db.prepare(`UPDATE services SET short_description=?, description=?, updated_at=datetime('now') WHERE id=?`);
  for (const u of updates) {
    stmt.run(u.short_description, u.description, u.id, function(err) {
      if (err) console.error(`ERROR id=${u.id}:`, err.message);
      else console.log(`OK id=${u.id} (${this.changes} row updated)`);
    });
  }
  stmt.finalize();
});

db.close(() => {
  console.log('\nВсе описания обновлены. Перезапустите pm2 restart arenda-neba');
});
